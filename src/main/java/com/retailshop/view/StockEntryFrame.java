    private void btnSaveStockActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveStockActionPerformed
ComboItem product =
        (ComboItem) cmbProduct.getSelectedItem();

ComboItem employee =
        (ComboItem) cmbEmployee.getSelectedItem();

if (product == null || employee == null) {
    JOptionPane.showMessageDialog(
        this, "Select a product and employee."
    );
    return;
}

final int quantity;

try {
    quantity = Integer.parseInt(
        txtQuantity.getText().trim()
    );

    if (quantity <= 0) {
        JOptionPane.showMessageDialog(
            this, "Quantity must be greater than zero."
        );
        return;
    }

} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(
        this, "Enter a whole number for quantity."
    );
    return;
}

final String notes = txtNotes.getText().trim();

if (notes.length() > 255) {
    JOptionPane.showMessageDialog(
        this, "Notes must not exceed 255 characters."
    );
    return;
}

int answer = JOptionPane.showConfirmDialog(
    this,
    "Add " + quantity + " units to " + product + "?",
    "Confirm Stock Entry",
    JOptionPane.YES_NO_OPTION
);

if (answer != JOptionPane.YES_OPTION) {
    return;
}

btnSaveStock.setEnabled(false);
btnClear.setEnabled(false);
cmbProduct.setEnabled(false);
cmbEmployee.setEnabled(false);
txtQuantity.setEnabled(false);
txtNotes.setEnabled(false);

new SwingWorker<Void, Void>() {

    @Override
    protected Void doInBackground() throws Exception {
        new StockService().addStock(
            product.getId(),
            employee.getId(),
            quantity,
            notes
        );

        return null;
    }

    @Override
    protected void done() {
        try {
            get();

            txtQuantity.setText("1");
            txtNotes.setText("");

            JOptionPane.showMessageDialog(
                StockEntryFrame.this,
                "Stock entry saved successfully!"
            );

        } catch (Exception ex) {
            ex.printStackTrace();

            Throwable cause = ex.getCause();

            String message =
                "Could not save stock. Check the Output panel.";

            if (cause instanceof ValidationException) {
                message = cause.getMessage();
            }

            JOptionPane.showMessageDialog(
                StockEntryFrame.this,
                message,
                "Stock Error",
                JOptionPane.ERROR_MESSAGE
            );

        } finally {
            btnClear.setEnabled(true);
            txtQuantity.setEnabled(true);
            txtNotes.setEnabled(true);

            cmbProduct.setEnabled(
                cmbProduct.getItemCount() > 0
            );

            cmbEmployee.setEnabled(
                cmbEmployee.getItemCount() > 0
            );

            btnSaveStock.setEnabled(
                cmbProduct.getSelectedItem() != null
                && cmbEmployee.getSelectedItem() != null
            );
        }
    }

}.execute();        // TODO add your handling code here:
    }//GEN-LAST:event_btnSaveStockActionPerformed

