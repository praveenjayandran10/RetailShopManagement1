    private void loadDashboard() {

    btnRefresh.setEnabled(false);

    new SwingWorker<Void, Void>() {

        private int productCount;
        private BigDecimal todaySales;
        private DefaultTableModel lowStock;

        @Override
        protected Void doInBackground() throws Exception {
            DashboardDAO dao = new DashboardDAO();

            productCount = dao.getProductCount();
            todaySales = dao.getTodaySales();
            lowStock = dao.getLowStock();

            return null;
        }

        @Override
        protected void done() {
            try {
                get();

                lblProductCount.setText(
                    String.valueOf(productCount)
                );

                lblTodaySales.setText(
                    todaySales.setScale(2).toPlainString()
                );

                tblLowStock.setModel(lowStock);

            } catch (Exception ex) {
                ex.printStackTrace();

                JOptionPane.showMessageDialog(
                    DashboardFrame.this,
                    "Could not load dashboard data. "
                        + "Check the Output panel.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
                );

            } finally {
                btnRefresh.setEnabled(true);
            }
        }

    }.execute();
}
