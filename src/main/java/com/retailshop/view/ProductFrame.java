    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
int selectedRow = tblProducts.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(
        this, "Select a product to delete."
    );
    return;
}

int row = tblProducts.convertRowIndexToModel(selectedRow);

final int id = ((Number) tblProducts.getModel()
        .getValueAt(row, 0)).intValue();

String name = tblProducts.getModel()
        .getValueAt(row, 1).toString();

int answer = JOptionPane.showConfirmDialog(
    this,
    "Delete \"" + name + "\"?",
    "Confirm Delete",
    JOptionPane.YES_NO_OPTION,
    JOptionPane.WARNING_MESSAGE
);

if (answer != JOptionPane.YES_OPTION) {
    return;
}

btnAdd.setEnabled(false);
btnUpdate.setEnabled(false);
btnDelete.setEnabled(false);
btnClear.setEnabled(false);
tblProducts.setEnabled(false);

new SwingWorker<Void, Void>() {

    @Override
    protected Void doInBackground() throws Exception {
        new ProductController().delete(id);
        return null;
    }

    @Override
    protected void done() {
        try {
            get();

            clearFields();
            loadProducts();

            JOptionPane.showMessageDialog(
                ProductFrame.this, "Product deleted successfully."
            );

        } catch (Exception ex) {
            ex.printStackTrace();

            Throwable cause = ex.getCause();

            if (cause instanceof java.sql.SQLException
                    && ((java.sql.SQLException) cause)
                        .getErrorCode() == 1451) {

                JOptionPane.showMessageDialog(
                    ProductFrame.this,
                    "This product is used in a sale and cannot be deleted."
                );

            } else {
                JOptionPane.showMessageDialog(
                    ProductFrame.this,
                    "Could not delete the product. Check the Output panel.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
                );
            }

        } finally {
            btnAdd.setEnabled(true);
            btnClear.setEnabled(true);
            tblProducts.setEnabled(true);

            boolean selected = tblProducts.getSelectedRow() != -1;
            btnUpdate.setEnabled(selected);
            btnDelete.setEnabled(selected);
        }
    }

}.execute();        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteActionPerformed

