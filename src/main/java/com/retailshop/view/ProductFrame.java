    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
String name = txtName.getText().trim();
String category = txtCategory.getText().trim();

if (name.isEmpty() || name.length() > 100) {
    JOptionPane.showMessageDialog(
        this, "Enter a product name of 1 to 100 characters."
    );
    return;
}

if (category.isEmpty() || category.length() > 50) {
    JOptionPane.showMessageDialog(
        this, "Enter a category of 1 to 50 characters."
    );
    return;
}

final java.math.BigDecimal price;
final int stock;

try {
    price = new java.math.BigDecimal(txtPrice.getText().trim());
    stock = Integer.parseInt(txtStock.getText().trim());

    if (price.signum() <= 0 || price.scale() > 2
            || price.compareTo(
                new java.math.BigDecimal("99999999.99")) > 0) {
        JOptionPane.showMessageDialog(
            this, "Enter a positive price with up to 2 decimal places."
        );
        return;
    }

    if (stock < 0) {
        JOptionPane.showMessageDialog(
            this, "Stock quantity cannot be negative."
        );
        return;
    }

} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(
        this, "Enter a valid price and a whole number for stock."
    );
    return;
}

btnAdd.setEnabled(false);

new SwingWorker<Void, Void>() {

    @Override
    protected Void doInBackground() throws Exception {
        new ProductController().add(name, category, price, stock);
        return null;
    }

    @Override
    protected void done() {
        try {
            get();

            txtName.setText("");
            txtCategory.setText("");
            txtPrice.setText("");
            txtStock.setText("");

            loadProducts();

            JOptionPane.showMessageDialog(
                ProductFrame.this, "Product added successfully!"
            );

        } catch (Exception ex) {
            ex.printStackTrace();

            JOptionPane.showMessageDialog(
                ProductFrame.this,
                "Could not save the product. Check the Output panel.",
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );

        } finally {
            btnAdd.setEnabled(true);
        }
    }

}.execute();

// TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

