private void loadCustomers() {
    new SwingWorker<DefaultTableModel, Void>() {

        @Override
        protected DefaultTableModel doInBackground() throws Exception {
            return new CustomerController().getAll();
        }

        @Override
        protected void done() {
            try {
                tblCustomers.setModel(get());

            } catch (Exception ex) {
                ex.printStackTrace();

                JOptionPane.showMessageDialog(
                    CustomerFrame.this,
                    "Could not load customers. Check the Output panel.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
                );
            }
        }

    }.execute();
}
    



