    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
final String name = txtName.getText().trim();
final String phone = txtPhone.getText().trim();
final String email = txtEmail.getText().trim();

if (name.isEmpty() || name.length() > 100) {
    JOptionPane.showMessageDialog(
        this, "Enter a customer name of 1 to 100 characters."
    );
    return;
}

if (!phone.isEmpty()
        && !phone.matches("\\+?[0-9]{7,15}")) {

    JOptionPane.showMessageDialog(
        this, "Enter 7 to 15 phone digits, optionally starting with +."
    );
    return;
}

if (!email.isEmpty()
        && (email.length() > 100
        || !email.matches("^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$"))) {

    JOptionPane.showMessageDialog(
        this, "Enter a valid email address."
    );
    return;
}

btnAdd.setEnabled(false);

new SwingWorker<Void, Void>() {

    @Override
    protected Void doInBackground() throws Exception {
        new CustomerController().add(name, phone, email);
        return null;
    }

    @Override
    protected void done() {
        try {
            get();

            txtName.setText("");
            txtPhone.setText("");
            txtEmail.setText("");

            loadCustomers();

            JOptionPane.showMessageDialog(
                CustomerFrame.this,
                "Customer added successfully!"
            );

        } catch (Exception ex) {
            ex.printStackTrace();

            JOptionPane.showMessageDialog(
                CustomerFrame.this,
                "Could not save the customer. Check the Output panel.",
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );

        } finally {
            btnAdd.setEnabled(true);
        }
    }

}.execute();        // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

