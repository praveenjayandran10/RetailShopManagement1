    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {                                          
int selectedRow = tblEmployees.getSelectedRow();

if (selectedRow == -1) {
    JOptionPane.showMessageDialog(
        this, "Select an employee to delete."
    );
    return;
}

int row = tblEmployees.convertRowIndexToModel(selectedRow);

final int id = ((Number) tblEmployees.getModel()
        .getValueAt(row, 0)).intValue();

String name = tblEmployees.getModel()
        .getValueAt(row, 1).toString();

int answer = JOptionPane.showConfirmDialog(
    this,
    "Delete employee \"" + name + "\"?",
    "Confirm Delete",
    JOptionPane.YES_NO_OPTION,
    JOptionPane.WARNING_MESSAGE
);

if (answer != JOptionPane.YES_OPTION) {
    return;
}

btnAdd.setEnabled(false);
btnUpdate.setEnabled(false);
btnDelete.setEnabled(false);
btnClear.setEnabled(false);
tblEmployees.setEnabled(false);
txtName.setEnabled(false);
cmbRole.setEnabled(false);

new SwingWorker<Void, Void>() {

    @Override
    protected Void doInBackground() throws Exception {
        new EmployeeController().delete(id);
        return null;
    }

    @Override
    protected void done() {
        try {
            get();

            clearFields();
            loadEmployees();

            JOptionPane.showMessageDialog(
                EmployeeFrame.this,     
                "Employee deleted successfully."
            );

        } catch (Exception ex) {
            ex.printStackTrace();

            Throwable cause = ex.getCause();

            if (cause instanceof java.sql.SQLException
                    && ((java.sql.SQLException) cause)
                        .getErrorCode() == 1451) {

                JOptionPane.showMessageDialog(
                    EmployeeFrame.this,
                    "This employee has sales or stock-entry records "
                        + "and cannot be deleted."
                );

            } else {
                JOptionPane.showMessageDialog(
                    EmployeeFrame.this,
                    "Could not delete the employee. "
                        + "Check the Output panel.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
                );
            }

        } finally {
            btnAdd.setEnabled(true);
            btnClear.setEnabled(true);
            tblEmployees.setEnabled(true);
            txtName.setEnabled(true);
            cmbRole.setEnabled(true);

            boolean selected =
                tblEmployees.getSelectedRow() != -1;

            btnUpdate.setEnabled(selected);
            btnDelete.setEnabled(selected);
        }
    }

}.execute();        // TODO add your handling code here:
    }                                         

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {                                       
final String name = txtName.getText().trim();
final String role = (String) cmbRole.getSelectedItem();

if (name.isEmpty() || name.length() > 100) {
    JOptionPane.showMessageDialog(
        this, "Enter an employee name of 1 to 100 characters."
    );
    return;
}

if (role == null
        || !(role.equals("Cashier")
        || role.equals("Manager")
        || role.equals("Stock Clerk"))) {

    JOptionPane.showMessageDialog(
        this, "Select a valid employee role."
    );
    return;
}

btnAdd.setEnabled(false);
btnUpdate.setEnabled(false);
btnDelete.setEnabled(false);
btnClear.setEnabled(false);
tblEmployees.setEnabled(false);
txtName.setEnabled(false);
cmbRole.setEnabled(false);

new SwingWorker<Void, Void>() {

    @Override
    protected Void doInBackground() throws Exception {
        new EmployeeController().add(name, role);
        return null;
    }

    @Override
    protected void done() {
        try {
            get();

            txtName.setText("");
            cmbRole.setSelectedIndex(0);
            tblEmployees.clearSelection();

            loadEmployees();

            JOptionPane.showMessageDialog(
                EmployeeFrame.this,
                "Employee added successfully!"
            );

        } catch (Exception ex) {
            ex.printStackTrace();

            JOptionPane.showMessageDialog(
                EmployeeFrame.this,
                "Could not save the employee. Check the Output panel.",
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );

        } finally {
            btnAdd.setEnabled(true);
            btnClear.setEnabled(true);
            tblEmployees.setEnabled(true);
            txtName.setEnabled(true);
            cmbRole.setEnabled(true);

            // Update and Delete will be connected next.
        }
    }

}.execute();        // TODO add your handling code here:
    }                                      

