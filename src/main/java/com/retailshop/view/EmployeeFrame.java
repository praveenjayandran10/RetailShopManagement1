    private void loadEmployees() {

    new SwingWorker<DefaultTableModel, Void>() {

        @Override
        protected DefaultTableModel doInBackground() throws Exception {
            return new EmployeeController().getAll();
        }

        @Override
        protected void done() {
            try {
                tblEmployees.setModel(get());

            } catch (Exception ex) {
                ex.printStackTrace();

                JOptionPane.showMessageDialog(
                    EmployeeFrame.this,
                    "Could not load employees. Check the Output panel.",
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
                );
            }
        }

    }.execute();
    
}
