    private void btnViewReportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewReportActionPerformed
final LocalDate fromDate;
final LocalDate toDate;
final LocalDate endExclusive;

try {
    fromDate = LocalDate.parse(
        txtFromDate.getText().trim()
    );

    toDate = LocalDate.parse(
        txtToDate.getText().trim()
    );

    if (fromDate.isAfter(toDate)) {
        JOptionPane.showMessageDialog(
            this, "From Date must not be after To Date."
        );
        return;
    }

    if (fromDate.getYear() < 1000 || toDate.getYear() > 9998) {
        JOptionPane.showMessageDialog(
            this, "Use dates between years 1000 and 9998."
        );
        return;
    }

    endExclusive = toDate.plusDays(1);

} catch (DateTimeParseException ex) {
    JOptionPane.showMessageDialog(
        this, "Enter valid dates in yyyy-MM-dd format."
    );
    return;
}

btnViewReport.setEnabled(false);

new SwingWorker<JasperPrint, Void>() {

    @Override
    protected JasperPrint doInBackground() throws Exception {

        try (InputStream input =
                 ReportFrame.class.getResourceAsStream(
                     "/reports/sales_report.jrxml");
             Connection connection =
                 DBConnection.getConnection()) {

            if (input == null) {
                throw new IllegalStateException(
                    "Report template was not found."
                );
            }

            Map<String, Object> parameters = new HashMap<>();

            parameters.put(
                "FROM_DATE",
                Timestamp.valueOf(fromDate.atStartOfDay())
            );

            parameters.put(
                "TO_DATE_EXCLUSIVE",
                Timestamp.valueOf(endExclusive.atStartOfDay())
            );

            var report =
                JasperCompileManager.compileReport(input);

            return JasperFillManager.fillReport(
                report, parameters, connection
            );
        }
    }

    @Override
    protected void done() {
        try {
            JasperPrint report = get();

            // false means closing the viewer won't exit the app.
            JasperViewer.viewReport(report, false);

        } catch (Exception ex) {
            ex.printStackTrace();

            JOptionPane.showMessageDialog(
                ReportFrame.this,
                "Could not generate the report. "
                    + "Check the Output panel.",
                "Report Error",
                JOptionPane.ERROR_MESSAGE
            );

        } finally {
            btnViewReport.setEnabled(true);
        }
    }

}.execute();        // TODO add your handling code here:
    }//GEN-LAST:event_btnViewReportActionPerformed

